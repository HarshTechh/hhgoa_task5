export function searchFoodDatabase(query: string, dietFilter?: string): FoodItem[] {
  if (!query || query.trim() === '') return VERIFIED_FOOD_DATABASE.slice(0, 15);
  const q = query.toLowerCase().trim();

  return VERIFIED_FOOD_DATABASE.filter(item => {
    const nameMatch = item.name.toLowerCase().includes(q);
    const aliasMatch = item.aliases?.some(a => a.toLowerCase().includes(q));
    const cuisineMatch = item.cuisine.toLowerCase().includes(q);
    const matchesText = nameMatch || aliasMatch || cuisineMatch;

    if (!matchesText) return false;
    if (dietFilter && dietFilter !== 'all') {
      if (dietFilter === 'vegetarian' && item.dietType === 'non_vegetarian') return false;
      if (dietFilter === 'vegan' && item.dietType !== 'vegan') return false;
      if (dietFilter === 'eggetarian' && item.dietType === 'non_vegetarian') return false;
    }
    return true;
  });
}
